STEM_OF = {'diegetic (air, Earth)': 'ambience_mechanical', 'non-diegetic music bed': 'music_bed', 'transition': 'illustrative_fx', 'suspense': 'illustrative_fx',
           'illustrative accent': 'illustrative_fx', 'reveal accent': 'illustrative_fx', 'illustrative data sound': 'illustrative_fx', 'measurement': 'illustrative_fx'}

def read_wav(p):
    out = subprocess.run(['ffmpeg', '-v', 'error', '-i', p, '-f', 'f32le', '-ac', '1', '-ar', str(SR), '-'], capture_output=True, check=True).stdout
    return np.frombuffer(out, np.float32).astype(np.float64)

def ebur(p):
    r = subprocess.run(['ffmpeg', '-hide_banner', '-nostats', '-i', p, '-af', 'ebur128=peak=true', '-f', 'null', '-'], capture_output=True, text=True).stderr
    I = re.findall(r'I:\s+(-?[\d.]+) LUFS', r); TP = re.findall(r'Peak:\s+(-?[\d.]+|-inf) dBFS', r); LRA = re.findall(r'LRA:\s+(-?[\d.]+) LU', r)
    return dict(I=float(I[-1]) if I else None, TP=float(TP[-1]) if TP and TP[-1] != '-inf' else None, LRA=float(LRA[-1]) if LRA else None)

def main():
    L = lib(); cs = cue_list()
    stems = {k: np.zeros(N) for k in set(STEM_OF.values())}
    for c in cs:
        x = L[c['file']] * db(c['gain_db'] + 6 + BED_TRIM)   # library files peak at -6..-10 dBFS; BED_TRIM: global bed level (V2: +6 after the first pass measured 32 dB voice-to-bed in speech, likely inaudible on phones)
        if c['file'].startswith('ambience/'):
            seg_end = 9.9 if c['t'] < 10 else 60.6
            ln = int(SR * (seg_end - c['t'])); x = np.resize(x, ln) * np.clip(np.arange(ln) / (SR * 0.4), 0, 1) * np.clip((ln - np.arange(ln)) / (SR * 0.6), 0, 1)
        i0 = int(SR * c['t']); x = x[:max(0, N - i0)]; stems[STEM_OF[c['kind']]][i0:i0 + len(x)] += x
    # intentional silence: pull everything out around "But hold on" (31.0-31.65) except the hold-breath cue itself
    hold = np.ones(N); t = np.arange(N) / SR; m = (t > NAR.start('B14') - 0.15) & (t < NAR.end('B14') + 0.1)
    hold[m] = 0.25
    for k in ('music_bed', 'ambience_mechanical'): stems[k] *= lp(hold, 6)
    # dialogue-first ducking + anti-masking (extra cut of the 1-4 kHz band of the bed while speech is present)
    nar = read_wav(MASTER_WAV); nar = np.pad(nar, (0, max(0, N - len(nar))))[:N]
    e = lfilter([1 - np.exp(-2 * np.pi * 8 / SR)], [1, -np.exp(-2 * np.pi * 8 / SR)], np.abs(nar)); e = e / (e.max() + 1e-9)
    speech = np.clip(e / 0.08, 0, 1); duck = lp(db(-8) + (1 - db(-8)) * (1 - speech), 4)
    bed = sum(stems.values()); band = bp(bed, 1000, 4000); bed_d = (bed - band) * duck + band * duck * lp(1 - 0.5 * speech, 4)
    mix = nar + bed_d
    os.makedirs(os.path.join(OUT, 'stems'), exist_ok=True)
    write(os.path.join(OUT, 'stems', 'stem_narration_v2_master.wav'), nar)
    for k, v in stems.items():                                          # stems are written ducked the same way as the mix, so they sum to the mix
        vb = bp(v, 1000, 4000); write(os.path.join(OUT, 'stems', 'stem_%s.wav' % k), (v - vb) * duck + vb * duck * lp(1 - 0.5 * speech, 4))
    write(os.path.join(OUT, 'stems', 'stem_sfx_bed_total.wav'), bed_d)
    pre = os.path.join(OUT, 'final_mix_v2_premaster.wav'); write(pre, mix / max(1.0, np.abs(mix).max() / db(-1)))
    # loudness (V2): static gain to -16 LUFS integrated + a transparent peak limiter on the rare speech transients (loudnorm's
    # 'linear' mode cannot reach -16 with the raw take's -0.7 dBTP peaks and silently falls back to dynamic compression of the voice).
    I0 = ebur(pre)['I']; g = -16.0 - I0; fin = os.path.join(OUT, 'final_mix_v2.wav')
    for lim in (-2.0, -2.5, -3.0):
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', pre, '-af', 'aresample=192000,volume=%.2fdB,alimiter=limit=%.4f:attack=0.5:release=40:level=false,aresample=%d' % (g, db(lim), SR), fin], check=True)
        if ebur(fin)['TP'] <= -1.0: break
    xf = read_wav(fin); xp = read_wav(pre) * db(g); j = dict(premaster_I=I0, gain_db=round(g, 2), limiter_ceiling_dbfs=lim,
         samples_limited_pct=round(100 * float(np.mean(np.abs(xp) > db(lim))), 3))
    rep = dict(narration=ebur(MASTER_WAV), sfx_bed=ebur(os.path.join(OUT, 'stems', 'stem_sfx_bed_total.wav')), mix_premaster=ebur(pre), final=ebur(fin),
               loudness_stage=j, duck_db=-8, speech_band_extra_cut_db=-6, target='-16 LUFS integrated, true peak <= -1.0 dBTP, static gain + transparent limiter (4x oversampled)',
               sources='all synthesised in tools/sound_design_v2.py (rights-clear); no third-party audio in the publication mix',
               cues=len(cs), listening_verified=False)
    rep['voice_minus_bed_LU'] = round(rep['narration']['I'] - rep['sfx_bed']['I'], 1)
    # speech-time separation: narration RMS vs bed RMS over frames where speech is present
    sp = speech > 0.5; rep['speech_time_voice_to_bed_db'] = round(20 * np.log10(np.sqrt(np.mean(nar[sp] ** 2)) / (np.sqrt(np.mean(bed_d[sp] ** 2)) + 1e-12)), 1)
    json.dump(rep, open(os.path.join(OUT, 'ROUGH_CUT_V2_mix_report.json'), 'w'), indent=1)
    with open(os.path.join(ROOT, 'SOUND_DESIGN_CUE_SHEET.csv'), 'w', newline='') as f:
        w = csv.writer(f); w.writerow(['cue', 'time_s', 'file', 'gain_db', 'kind', 'stem', 'narration_at_time', 'purpose'])
        for i, c in enumerate(cs, 1):
            p = NAR.phrase_at(c['t']); txt = ' '.join(x['word'] for x in NAR.words[p['first']:p['last'] + 1]) if p else '(no speech)'
            w.writerow(['S%03d' % i, '%.2f' % c['t'], 'audio/sfx/' + c['file'], c['gain_db'], c['kind'], STEM_OF[c['kind']], txt, c['why']])
    print(json.dumps({k: rep[k] for k in ('narration', 'sfx_bed', 'final', 'voice_minus_bed_LU', 'speech_time_voice_to_bed_db', 'cues')}, indent=1))

if __name__ == '__main__': main()
