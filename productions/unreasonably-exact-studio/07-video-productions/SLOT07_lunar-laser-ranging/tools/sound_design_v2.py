"""Sound design V2: an original, synthesised SFX library (audio/sfx/<category>/), a cue sheet, stems and a dialogue-first mix.

Every sound is generated by this script (rights-clear: no third-party audio). Rules kept from V1:
  * literal (diegetic) sound only where there is air: the observatory on Earth;
  * space and the Moon are silent: the pulse, the reflector and the astronaut get NO literal sounds; anything heard there is an
    ILLUSTRATIVE musical accent (soft tones), never a whoosh, impact or footstep;
  * narration is never processed; the bed is ducked under it, with an extra cut in the 1-4 kHz speech band (anti-masking).
Outputs: audio/sfx/**.wav, renders/roughcut_v2/{stems/*.wav, final_mix_v2.wav, ROUGH_CUT_V2_mix_report.json}, SOUND_DESIGN_CUE_SHEET.csv
"""
import csv, json, os, re, subprocess, sys, wave
import numpy as np
from scipy.signal import butter, sosfilt, lfilter
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, os.path.join(ROOT, 'animation'))
from uemotion.narration import MASTER_WAV, NAR
from proofs import opening as OP, p09, p06, gaps as G
BED_TRIM = 6.0
SR = 48000; DUR = 96.0; N = int(SR * DUR); rng = np.random.default_rng(2026)
LIB = os.path.join(ROOT, 'audio', 'sfx'); OUT = os.path.join(ROOT, 'renders', 'roughcut_v2')
def db(x): return 10 ** (x / 20)
def bp(x, lo, hi, o=2): return sosfilt(butter(o, [lo, hi], 'band', fs=SR, output='sos'), x)
def lp(x, f, o=2): return sosfilt(butter(o, f, 'low', fs=SR, output='sos'), x)
def hp(x, f, o=2): return sosfilt(butter(o, f, 'high', fs=SR, output='sos'), x)
def tt(d): return np.arange(int(SR * d)) / SR
def adsr(d, a=0.01, r=0.3):
    t = tt(d); return np.clip(t / a, 0, 1) * np.clip((d - t) / r, 0, 1)
def norm(x, peak_db=-6): return x / (np.abs(x).max() + 1e-12) * db(peak_db)
def write(p, x):
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with wave.open(p, 'wb') as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes((np.clip(x, -1, 1) * 32767).astype(np.int16).tobytes())

# ============================================================ library (one-shots and loops), all synthesised
def tone(f, d, dec=0.6, partials=((1, 1.0), (2.01, 0.25), (3.0, 0.08)), a=0.005):
    t = tt(d); e = np.exp(-t / dec) * np.clip(t / a, 0, 1)
    return sum(g * np.sin(2 * np.pi * f * m * t) for m, g in partials) * e
def lib():
    L = {}
    t = tt(8.5)                                                                         # curiosity: low evolving pad (A2 + E3 + B3, slow detune shimmer)
    pad = sum(np.sin(2 * np.pi * f * t + 0.8 * np.sin(2 * np.pi * 0.11 * t + k)) for k, f in enumerate((110.0, 164.81, 246.94, 110.4)))
    pad = lp(pad, 900) * (0.6 + 0.4 * np.sin(2 * np.pi * 0.07 * t) ** 2) * adsr(8.5, 1.8, 2.5)
    L['curiosity/curiosity_pad_low.wav'] = norm(pad, -8)
    q = np.zeros(int(SR * 1.6))                                                         # curiosity: three soft glassy notes rising (E5 A5 B5)
    for k, f in enumerate((659.25, 880.0, 987.77)):
        s = tone(f, 1.6 - 0.18 * k, 0.5); q[int(SR * 0.18 * k):int(SR * 0.18 * k) + len(s)] += s * (0.8 - 0.15 * k)
    L['curiosity/question_glass_rise.wav'] = norm(q, -8)
    nn = np.zeros(int(SR * 0.7))                                                        # playful negative: two muted notes falling a minor third (no buzzer)
    for k, f in enumerate((523.25, 440.0)):
        s = tone(f, 0.45, 0.12, ((1, 1), (4.0, 0.15)), 0.003); nn[int(SR * 0.16 * k):int(SR * 0.16 * k) + len(s)] += s
    L['curiosity/not_this_two_note.wav'] = norm(lp(nn, 3000), -8)
    d = 2.6; t = tt(d); x = rng.standard_normal(len(t))                                 # suspense: soft rise (filtered air + rising sine), stops dead (silence after)
    air = np.concatenate([bp(x[i:i + 4800], 300 + 1500 * i / len(t), 600 + 3000 * i / len(t)) for i in range(0, len(t), 4800)]).astype(float)[:len(t)] * (t / d) ** 2
    ris = np.sin(2 * np.pi * np.cumsum(220 * 2 ** (t / d)) / SR) * (t / d) ** 2.5 * 0.4
    L['suspense/soft_rise_to_silence.wav'] = norm((air * 0.6 + ris) * np.clip((d - t) / 0.02, 0, 1), -8)
    d = 1.4; t = tt(d)                                                                  # suspense: 'hold on' low muted pulse (a held breath)
    L['suspense/hold_breath_low.wav'] = norm(lp(np.sin(2 * np.pi * 73.4 * t) * np.exp(-t / 0.5) + 0.3 * np.sin(2 * np.pi * 110 * t) * np.exp(-t / 0.3), 400), -8)
    d = 10.0; x = rng.standard_normal(int(SR * d))                                      # ambience: night air on a mountain (wind + far hiss), loopable texture
    wind = lp(x, 240) * (0.7 + 0.3 * np.sin(2 * np.pi * 0.09 * tt(d) + 1.0)) + hp(lp(x, 5000), 2500) * 0.04
    L['ambience/observatory_night_air.wav'] = norm(wind * adsr(d, 0.5, 0.5), -10)
    def motor(d, f0, rise, noise_f):
        t = tt(d); f = f0 * (1 + (rise - 1) * t / d); ph = 2 * np.pi * np.cumsum(f) / SR
        return (0.6 * np.sin(ph) + 0.3 * np.sin(2 * ph) + 0.12 * lp(rng.standard_normal(len(t)), noise_f)) * adsr(d, 0.08, 0.15)
    L['mechanical/dome_shutter_motor.wav'] = norm(motor(0.9, 55, 1.08, 400), -8)        # diegetic (in air)
    L['mechanical/telescope_servo.wav'] = norm(motor(1.85, 140, 1.15, 900), -8)
    t = tt(0.25); L['mechanical/shutter_end_stop.wav'] = norm(lp(rng.standard_normal(len(t)), 300) * np.exp(-t / 0.04) + 0.5 * np.sin(2 * np.pi * 62 * t) * np.exp(-t / 0.08), -8)
    t = tt(0.12); L['mechanical/laser_fire_tick.wav'] = norm(np.sin(2 * np.pi * 2200 * t) * np.exp(-t / 0.05), -8)   # electronics click at the laser (on Earth)
    d = 1.2; t = tt(d); x = rng.standard_normal(len(t))                                  # transition: a soft swell of filtered air (not a whoosh: no pitch sweep, no doppler)
    L['transitions/soft_air_swell.wav'] = norm(bp(x, 200, 1200) * np.sin(np.pi * t / d) ** 2, -10)
    L['scientific_reveals/reveal_bell_e5.wav'] = norm(tone(659.25, 2.2, 1.1), -8)
    L['scientific_reveals/reveal_bell_c5.wav'] = norm(tone(523.25, 2.2, 1.1), -8)
    t = tt(3.0); ch = sum(tone(f, 3.0, 1.4) * g for f, g in ((392.0, 1.0), (493.88, 0.7), (587.33, 0.6), (783.99, 0.35)))   # G major add (final payoff)
    L['scientific_reveals/payoff_chord_g.wav'] = norm(ch, -8)
    t = tt(2.4); dy = tone(440.0, 2.4, 1.2) + 0.7 * tone(659.25, 2.4, 1.2)                # 'about two and a half seconds': open fifth, satisfying not triumphant
    L['scientific_reveals/answer_fifth_a.wav'] = norm(dy, -8)
    t = tt(0.4); L['scientific_reveals/pulse_glint_illustrative.wav'] = norm(np.sin(2 * np.pi * 1760 * t) * np.exp(-t / 0.12) * np.clip(t / 0.004, 0, 1), -10)  # illustrative, not 'the sound of light'
    t = tt(0.5); L['character_foley/settle_tone_illustrative.wav'] = norm(tone(196.0, 0.5, 0.18, ((1, 1), (2, 0.3))), -8)  # set-down on the Moon: a musical marker, not a thud (vacuum)
    t = tt(0.03); L['measurement/stopwatch_tick.wav'] = norm(np.sin(2 * np.pi * 3200 * t) * np.exp(-t / 0.012), -8)
    t = tt(0.35); L['measurement/detector_blip.wav'] = norm(tone(1318.5, 0.35, 0.08, ((1, 1), (2.0, 0.2))), -8)          # one detection event (illustrative data sound)
    t = tt(0.6); L['measurement/lock_click_tone.wav'] = norm(lp(rng.standard_normal(len(t)), 2500) * np.exp(-t / 0.01) * 0.4 + tone(987.77, 0.6, 0.25), -8)
    t = tt(0.9); L['measurement/corrected_tick.wav'] = norm(tone(783.99, 0.9, 0.3) + tone(1174.66, 0.9, 0.25) * 0.5, -8)
    for k, v in L.items(): write(os.path.join(LIB, k), v)
    return L

