HDR_B = ['id', 'brief_visual_concept', 'spoken_text', 'first_word', 'last_word', 'start_s', 'end_s', 'dur_s', 'pause_before_s', 'pause_after_s',
         'anchor_word', 'anchor_s', 'beat_type', 'emotion', 'reveal_opportunity', 'transition_opportunity']
HDR_V = ['id', 'start_s', 'anchor_s', 'required_assets', 'camera', 'animation_action', 'scientific_state', 'foreground',
         'midground', 'background', 'motion_graphics', 'sound_design', 'viewer_must_understand', 'model_class']

def f(x):
    return '%.2f' % x

rows_b, rows_v = [], []
for (bid, brief, a, b, anc, typ, emo, rev, tr, assets, cam, act, sci, fg, mg, bg, gfx, snd, und, mc) in B:
    s, e = W[a]['start'], W[b]['end']
    prev = W[a - 1]['end'] if a else 0.0
    nxt = W[b + 1]['start'] if b + 1 < len(W) else J['meta']['duration']
    anc_s = W[anc]['start']
    text = ' '.join(w['word'] for w in W[a:b + 1])
    rows_b.append([bid, brief, text, a, b, f(s), f(e), f(e - s), f(max(0, s - prev)), f(max(0, nxt - e)),
                   '%d:%s' % (anc, W[anc]['word']), f(anc_s), typ, emo, rev, tr])
    rows_v.append([bid, f(s), f(anc_s), ' '.join(USAGE[bid]), cam, act, sci, fg, mg, bg, gfx, snd, und, mc])

with open(ROOT / 'narration/NARRATION_BEAT_MAP.csv', 'w', newline='') as fh:
    w = csv.writer(fh); w.writerow(HDR_B); w.writerows(rows_b)
with open(ROOT / 'narration/NARRATION_TO_VISUAL_MAP.csv', 'w', newline='') as fh:
    w = csv.writer(fh); w.writerow(HDR_V); w.writerows(rows_v)

# coverage check: every spoken word belongs to exactly one beat, in order
cov = [0] * len(W)
for r in B:
    for i in range(r[2], r[3] + 1):
        cov[i] += 1
assert all(c == 1 for c in cov), [i for i, c in enumerate(cov) if c != 1]
print('beats', len(B), 'words covered', len(W))
