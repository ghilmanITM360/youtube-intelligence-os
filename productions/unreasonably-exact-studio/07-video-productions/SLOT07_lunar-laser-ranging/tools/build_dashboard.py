"""Single source of truth for Slot 07 status. Regenerates, from files on disk and three hand-kept CSVs:
  MASTER_PRODUCTION_DASHBOARD.md, ASSET_GENERATION_TRACKER.csv, ANIMATION_PROOF_REGISTER.md
Hand-kept inputs (edit these, never the generated outputs):
  qa/work_items.csv           id,area,item,state,evidence,next          state in COMPLETED|IN_PROGRESS|FAILED|BLOCKED|CANDIDATE|VALIDATED|HUMAN|PLANNED
  qa/asset_status_overrides.csv  asset_id,generation_status,rigging_status,validation_status,files,notes
  qa/proof_register.csv       proof_id,title,mechanism,status,mp4,frames,defects,corrections,retest,science_check,notes
Every 'evidence' path must exist or the item is shown as UNEVIDENCED. Run: python3 tools/build_dashboard.py
"""
import csv, os, glob, datetime, collections
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def P(*a): return os.path.join(ROOT, *a)
def rd(p):
    return list(csv.DictReader(open(P(p)))) if os.path.exists(P(p)) else []
def exists(ev):
    parts = [x.strip() for x in ev.replace(';', '|').split('|') if x.strip()]
    if not parts: return False
    ok = True
    for x in parts:
        ok &= bool(glob.glob(P(x))) if ('*' in x) else os.path.exists(P(x))
    return ok

BATCH = {'EARTH': 1, 'MOON': '1/3', 'RETRO': 2, 'OBS': 4, 'TEL': 4, 'ASTRO': 5}
man = rd('MASTER_ASSET_MANIFEST.csv'); ov = {r['asset_id']: r for r in rd('qa/asset_status_overrides.csv')}
import sys; sys.path.insert(0, P('tools'))
try:
    import brief_data
except Exception:
    brief_data = None
refs = rd('research/REFERENCE_MANIFEST.csv')
rows = []
for a in man:
    if a['kind'] == 'group': continue
    fam = a['asset_id'].split('_')[0]
    o = ov.get(a['asset_id'], {})
    bd = brief_data.get(a['asset_id']) if brief_data else None
    brief = 'codex_handoff/individual_asset_briefs/%s.md' % a['asset_id']
    tagged = sum(1 for r in refs if a['asset_id'] in r['asset_ids'].split() and r['local_filename'])
    rows.append(dict(asset_id=a['asset_id'], family=fam, kind=a['kind'], owner=a['responsible_agent'], priority=a['priority'],
        batch=BATCH.get(fam, '-') if a['responsible_agent'].startswith('Codex') else 'Claude-procedural',
        construction_method=(bd or {}).get('method', 'procedural code' if a['kind'] in ('code', 'model', 'rig') else ''),
        canvas=a['canvas_size'], brief=brief if os.path.exists(P(brief)) else '', refs_tagged=tagged,
        generation_status=o.get('generation_status', a['generation_status']), rigging_status=o.get('rigging_status', a['rigging_status']),
        validation_status=o.get('validation_status', a['validation_status']), files=o.get('files', ''), proof_clips=a['proof_clips'], notes=o.get('notes', '')))
cols = list(rows[0].keys())
with open(P('ASSET_GENERATION_TRACKER.csv'), 'w', newline='') as f:
    w = csv.DictWriter(f, cols); w.writeheader(); w.writerows(rows)

proofs = rd('qa/proof_register.csv')
with open(P('ANIMATION_PROOF_REGISTER.md'), 'w') as f:
    f.write('# Animation proof register (GENERATED by tools/build_dashboard.py from qa/proof_register.csv; do not edit)\n\n')
    f.write('A proof is `candidate` until the moving output was reviewed against its expected behaviour; nothing here is `approved` (only the owner approves). Required per proof: expected behaviour, actual MP4, start/middle/end frames, defects, corrections, re-test, scientific check.\n\n')
    f.write('| Proof | Title | Mechanism | Status | MP4 | Frames | Defects found | Corrections | Re-test | Science check |\n|---|---|---|---|---|---|---|---|---|---|\n')
    have = {p['proof_id']: p for p in proofs}
    for i in range(1, 14):
        pid = 'P%02d' % i; p = have.get(pid)
        if not p: f.write('| %s | (not started) | | NOT_STARTED | | | | | | |\n' % pid); continue
        mp4 = p['mp4'] if exists(p['mp4']) else ('MISSING: ' + p['mp4'] if p['mp4'] else '')
        f.write('| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n' % (pid, p['title'], p['mechanism'], p['status'], mp4, p['frames'], p['defects'], p['corrections'], p['retest'], p['science_check']))
    f.write('\nPer-proof reports live in `renders/proofs/<id>/PROOF_REPORT.md`.\n')

items = rd('qa/work_items.csv')
BUCKET = [('COMPLETED', 'Completed'), ('IN_PROGRESS', 'In progress'), ('FAILED', 'Failed'), ('BLOCKED', 'Blocked'), ('CANDIDATE', 'Candidate'), ('VALIDATED', 'Validated (automated evidence)'), ('HUMAN', 'Requires human verification (an agent cannot close these)'), ('PLANNED', 'Planned / not started')]
nfiles = sum(len(fs) for _, _, fs in os.walk(ROOT))
vc = collections.Counter(r['viewed'] for r in refs)
fc = collections.Counter(r['family'] for r in refs)
animx = rd('research/ANIMATION_EXAMPLES.csv'); am = collections.Counter(r['review_mode'] for r in animx)
ast = collections.Counter(r['generation_status'] for r in rows)
png_deliv = glob.glob(P('codex_handoff', 'deliveries', '**', '*.png'), recursive=True)
out = ['# MASTER PRODUCTION DASHBOARD (GENERATED; the one source of truth)', '',
       'Generated %s by `python3 tools/build_dashboard.py` from files on disk and `qa/work_items.csv`, `qa/asset_status_overrides.csv`, `qa/proof_register.csv`. **Edit those, not this file.** Other documents (START_HERE, PRODUCTION_PLAN, PROGRESS_LOG, ORIGINAL_BRIEF_COMPLIANCE_AUDIT, CODEX_HANDOFF) carry no status tables: they point here.' % datetime.datetime.now().strftime('%Y-%m-%d %H:%M'), '',
       '## Measured facts (counted by the script)', '',
       '| Fact | Value |', '|---|---|',
       '| Files in project tree | %d |' % nfiles,
       '| Reference manifest entries | %d (%s) |' % (len(refs), ', '.join('%s %d' % kv for kv in sorted(fc.items()))),
       '| ...with a local file | %d |' % sum(1 for r in refs if r['local_filename'] and os.path.exists(P(r['local_filename']))),
       '| ...marked viewed (opened) | %s viewed, %s not viewed |' % (vc.get('True', 0), vc.get('False', 0)),
       '| Animation examples | %d (%s) |' % (len(animx), ', '.join('%s %d' % kv for kv in sorted(am.items()))),
       '| Planned production assets (non-group) | %d (Codex %d, Claude %d) |' % (len(rows), sum(1 for r in rows if r['owner'].startswith('Codex')), sum(1 for r in rows if r['owner'] == 'Claude')),
       '| Codex briefs on disk | %d |' % len(glob.glob(P('codex_handoff', 'individual_asset_briefs', '*.md'))),
       '| Generated production artwork files (Codex deliveries, PNG) | %d |' % len(png_deliv),
       '| Validated rigs | %d |' % sum(1 for r in rows if r['rigging_status'] in ('MOTION_TESTED', 'APPROVED')),
       '| Proofs with an MP4 on disk | %d of 13 |' % sum(1 for p in proofs if exists(p['mp4'])),
       '| Asset generation_status | %s |' % ', '.join('%s %d' % kv for kv in sorted(ast.items())), '']
for k, title in BUCKET:
    sel = [i for i in items if i['state'] == k]
    out += ['## %s (%d)' % (title, len(sel)), '']
    if not sel: out += ['(none)', '']; continue
    out += ['| ID | Area | Item | Evidence | Next executable task |', '|---|---|---|---|---|']
    for i in sel:
        if k in ('HUMAN', 'PLANNED'): ev = i['evidence'] or '-'
        elif exists(i['evidence']): ev = i['evidence']
        elif k == 'IN_PROGRESS': ev = 'pending: %s (not on disk yet)' % i['evidence']
        else: ev = 'UNEVIDENCED (missing: %s)' % i['evidence']
        out.append('| %s | %s | %s | %s | %s |' % (i['id'], i['area'], i['item'], ev.replace('|', ' ; '), i['next']))
    out.append('')
open(P('MASTER_PRODUCTION_DASHBOARD.md'), 'w').write('\n'.join(out))
bad = [i['id'] for i in items if i['state'] not in ('HUMAN', 'PLANNED', 'IN_PROGRESS') and not exists(i['evidence'])]
print('dashboard written; items %d; unevidenced %s; assets %d; proofs %d' % (len(items), bad or 'none', len(rows), len(proofs)))
