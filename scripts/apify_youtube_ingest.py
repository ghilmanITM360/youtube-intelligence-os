def canonical_json(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def sha256_bytes(value):
    return hashlib.sha256(value).hexdigest()


def sanitize_input(actor_input):
    """Allowlist Actor input fields; credentials can never reach persistence."""
    return {key: actor_input[key] for key in sorted(actor_input) if key in SAFE_INPUT_KEYS}


def normalize_handle(value):
    if not value:
        return None
    value = str(value).strip()
    if "/@" in value:
        value = "@" + value.split("/@", 1)[1].split("/", 1)[0]
    if not value.startswith("@"):
        value = "@" + value
    return value


def handle_key(value):
    value = normalize_handle(value)
    return value.casefold() if value else None


def canonical_channel_url(value):
    if not value:
        return None
    parsed = urllib.parse.urlparse(str(value).strip())
    host = parsed.netloc.casefold().removeprefix("www.")
    if host not in {"youtube.com", "m.youtube.com"}:
        return None
    return "https://www.youtube.com" + parsed.path.rstrip("/").casefold()


def handle_from_url(value):
    parsed = urllib.parse.urlparse(value or "")
    part = parsed.path.strip("/").split("/", 1)[0]
    return normalize_handle(part) if part.startswith("@") else None


def parse_int(value, field):
    if value is None or value == "":
        return None
    if isinstance(value, bool):
        raise CatalogError("MalformedData", "{} must be an integer, not boolean".format(field))
    try:
        parsed = int(value)
    except (TypeError, ValueError):
        raise CatalogError("MalformedData", "{} is not an integer: {!r}".format(field, value))
    if parsed < 0:
        raise CatalogError("MalformedData", "{} cannot be negative: {}".format(field, parsed))
    return parsed


def parse_duration(value):
    if not value:
        return None
    parts = str(value).strip().split(":")
    if len(parts) not in (2, 3):
        raise CatalogError("MalformedData", "Unsupported duration: {!r}".format(value))
    try:
        numbers = [int(part) for part in parts]
    except ValueError:
        raise CatalogError("MalformedData", "Unsupported duration: {!r}".format(value))
    if any(number < 0 for number in numbers) or any(number > 59 for number in numbers[1:]):
        raise CatalogError("MalformedData", "Unsupported duration: {!r}".format(value))
    if len(numbers) == 2:
        return numbers[0] * 60 + numbers[1]
    return numbers[0] * 3600 + numbers[1] * 60 + numbers[2]


def normalize_transcript(subtitles):
    if not subtitles:
        return {
            "availability_status": "UNAVAILABLE", "caption_type": None,
            "language": None, "format": None, "text": None,
            "canonical_reference": None, "word_count": None,
        }
    choices = subtitles if isinstance(subtitles, list) else [subtitles]
    choices = [choice for choice in choices if isinstance(choice, dict)]
    if not choices:
        raise CatalogError("MalformedData", "subtitles must be an object, array, or null")
    selected = next((x for x in choices if str(x.get("language", "")).casefold().startswith("en")), choices[0])
    text = selected.get("plaintext")
    if text is not None and not isinstance(text, str):
        raise CatalogError("MalformedData", "subtitle plaintext must be text or null")
    text = text.strip() if text else None
    reference = selected.get("srtUrl") or selected.get("vttUrl") or selected.get("url")
    available = bool(text or reference)
    return {
        "availability_status": "AVAILABLE" if available else "UNAVAILABLE",
        "caption_type": selected.get("type"),
        "language": selected.get("language"),
        "format": "plaintext" if text else ("srt" if selected.get("srtUrl") else None),
        "text": text,
        "canonical_reference": reference,
        "word_count": len(re.findall(r"\b\w+\b", text, flags=re.UNICODE)) if text else None,
    }


def normalize_record(record, record_index):
    if not isinstance(record, dict):
        raise CatalogError("MalformedData", "Apify result {} is not an object".format(record_index))
    if record.get("error"):
        raise CatalogError("MalformedData", "Apify result {} is an error record: {}".format(record_index, record["error"]))
    youtube_video_id = record.get("id")
    if not isinstance(youtube_video_id, str) or not re.fullmatch(r"[A-Za-z0-9_-]{11}", youtube_video_id):
        raise CatalogError("MalformedData", "Apify result {} has invalid video id: {!r}".format(record_index, youtube_video_id))
    raw_type = record.get("type")
    list_page = record.get("fromChannelListPage")
    page_types = {
        "videos": ({None, "video"}, "video"),
        "shorts": ({None, "short", "shorts"}, "shorts"),
        "streams": ({None, "live", "stream", "streams"}, "stream"),
        "live": ({None, "live", "stream", "streams"}, "stream"),
    }
    if list_page in page_types:
        allowed, video_type = page_types[list_page]
        if raw_type not in allowed:
            raise CatalogError(
                "MalformedData",
                "Apify result {} has conflicting type/page: {!r}/{!r}".format(
                    record_index, raw_type, list_page
                ),
            )
    elif raw_type in (None, "video"):
        video_type = "video"
    elif raw_type in ("short", "shorts"):
        video_type = "shorts"
    elif raw_type in ("live", "stream", "streams"):
        video_type = "stream"
    else:
        raise CatalogError("MalformedData", "Apify result {} has unsupported content type {!r}".format(record_index, raw_type))
    title = record.get("title")
    channel_id = record.get("channelId") or (record.get("aboutChannelInfo") or {}).get("channelId")
    channel_name = record.get("channelName") or (record.get("aboutChannelInfo") or {}).get("channelName")
    if not isinstance(title, str) or not title.strip() or not channel_id or not channel_name:
        raise CatalogError("MalformedData", "Apify result {} is missing title/channel identity".format(record_index))
    about = record.get("aboutChannelInfo") or {}
    handle = normalize_handle(record.get("channelUsername") or about.get("channelUsername"))
    channel_url = record.get("channelUrl") or about.get("channelUrl")
    channel_video_count = record.get("channelTotalVideos")
    if channel_video_count is None:
        channel_video_count = about.get("channelTotalVideos")
    description = record.get("text")
    if description is not None and not isinstance(description, str):
        raise CatalogError("MalformedData", "Apify result {} description must be text or null".format(record_index))
    published_at = record.get("date")
    if published_at is not None and not isinstance(published_at, str):
        raise CatalogError("MalformedData", "Apify result {} publish date must be text or null".format(record_index))
    transcript = normalize_transcript(record.get("subtitles"))
    return {
        "record_index": record_index,
        "raw_record_sha256": sha256_bytes(canonical_json(record).encode("utf-8")),
        "youtube_video_id": youtube_video_id,
        "title": title.strip(),
        "youtube_channel_id": str(channel_id),
        "channel_name": str(channel_name).strip(),
        "handle": handle,
        "channel_url": channel_url,
        "canonical_url": record.get("url") or "https://www.youtube.com/watch?v={}".format(youtube_video_id),
        "published_at": published_at,
        "duration_seconds": parse_duration(record.get("duration")),
        "description": description,
        "video_type": video_type,
        "views": parse_int(record.get("viewCount"), "viewCount"),
        "likes": parse_int(record.get("likes"), "likes"),
        "comments": parse_int(record.get("commentsCount"), "commentsCount"),
        "subscribers": parse_int(record.get("numberOfSubscribers") if record.get("numberOfSubscribers") is not None else about.get("numberOfSubscribers"), "numberOfSubscribers"),
        "channel_video_count": parse_int(channel_video_count, "channelTotalVideos"),
        "thumbnail_urls": [record["thumbnailUrl"]] if isinstance(record.get("thumbnailUrl"), str) and record["thumbnailUrl"].strip() else [],
        "transcript": transcript,
    }


def validate_records(records):
    normalized, by_id, duplicates = [], {}, []
    for index, raw in enumerate(records):
        item = normalize_record(raw, index)
        prior = by_id.get(item["youtube_video_id"])
        if prior:
            compare_keys = set(item) - {"record_index", "raw_record_sha256"}
            if any(item[key] != prior[key] for key in compare_keys):
                raise CatalogError("EvidenceConflict", "Conflicting duplicate video id {}".format(item["youtube_video_id"]))
            duplicates.append(item["youtube_video_id"])
            continue
        by_id[item["youtube_video_id"]] = item
        normalized.append(item)
    if not normalized:
        raise CatalogError("MalformedData", "Actor returned no valid content records")

    def one_value(field):
        values = {item[field] for item in normalized if item[field] not in (None, "")}
        if len(values) > 1:
            raise CatalogError("EvidenceConflict", "Actor results contain conflicting {} values: {}".format(field, sorted(values)))
        return next(iter(values), None)

    channel = {
        "youtube_channel_id": one_value("youtube_channel_id"),
        "display_name": one_value("channel_name"),
        "handle": one_value("handle"),
        "channel_url": one_value("channel_url"),
        "subscriber_count": one_value("subscribers"),
        "video_count": one_value("channel_video_count"),
    }
    missing = {field: sum(item[field] in (None, "", []) for item in normalized) for field in (
        "title", "published_at", "duration_seconds", "description", "views", "likes", "comments", "thumbnail_urls"
    )}
    available = sum(item["transcript"]["availability_status"] == "AVAILABLE" for item in normalized)
    content_type_counts = {
        kind: sum(item["video_type"] == kind for item in normalized)
        for kind in ("video", "shorts", "stream")
    }
    return normalized, channel, {
        "returned_records": len(records),
        "unique_videos": len(normalized),
        "duplicate_video_ids": duplicates,
        "transcripts_available": available,
        "transcripts_unavailable": len(normalized) - available,
        "content_type_counts": content_type_counts,
        "missing_metadata": missing,
        "malformed_records": 0,
    }


def maximum_results_for_cap(price_per_video, cost_cap):
    price, cap = Decimal(str(price_per_video)), Decimal(str(cost_cap))
    if price <= 0 or cap <= 0:
        raise CatalogError("MalformedData", "price_per_video and cost_cap must be positive")
    return int((cap / price).to_integral_value(rounding=ROUND_FLOOR))


def enforce_cost_cap(max_results, price_per_video, cost_cap):
    maximum = maximum_results_for_cap(price_per_video, cost_cap)
    if max_results < 1 or max_results > maximum:
        raise CatalogError("CostCapExceeded", "{} results at ${} each exceeds ${} cap; maximum is {}".format(max_results, price_per_video, cost_cap, maximum))
    return Decimal(max_results) * Decimal(str(price_per_video))


