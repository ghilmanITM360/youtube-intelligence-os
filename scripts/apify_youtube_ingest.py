class ApifyHttp:
    def __init__(self, token):
        if not token:
            raise CatalogError("SecurityViolation", "APIFY_TOKEN MISSING")
        self._token = token

    def request(self, method, path, body=None, timeout=90):
        data = canonical_json(body).encode("utf-8") if body is not None else None
        request = urllib.request.Request(
            "https://api.apify.com" + path,
            data=data,
            method=method,
            headers={"Authorization": "Bearer " + self._token, "Content-Type": "application/json"},
        )
        try:
            with urllib.request.urlopen(request, timeout=timeout) as response:
                return json.loads(response.read().decode("utf-8"))
        except (urllib.error.URLError, urllib.error.HTTPError, json.JSONDecodeError) as exc:
            raise CatalogError("ToolFailure", "Apify API request failed: {}".format(type(exc).__name__))


def invoke_actor(client, actor_input, timeout_seconds=1800, max_total_charge_usd=None):
    path = "/v2/acts/{}/runs?waitForFinish=60".format(ACTOR_API_NAME)
    if max_total_charge_usd is not None:
        path += "&maxTotalChargeUsd={}".format(urllib.parse.quote(str(max_total_charge_usd)))
    response = client.request("POST", path, actor_input)
    run = response.get("data", response)
    run_id = run.get("id")
    if not run_id:
        raise CatalogError("ToolFailure", "Apify did not return an Actor run ID")
    deadline = time.monotonic() + timeout_seconds
    while run.get("status") not in TERMINAL_STATUSES:
        if time.monotonic() >= deadline:
            raise CatalogError("ToolFailure", "Timed out waiting for Apify run {}".format(run_id))
        time.sleep(2)
        run = client.request("GET", "/v2/actor-runs/{}".format(run_id)).get("data", {})
    dataset_id = run.get("defaultDatasetId")
    records = []
    if dataset_id:
        offset, page_size = 0, 25
        while True:
            page = client.request("GET", "/v2/datasets/{}/items?format=json&clean=false&limit={}&offset={}".format(dataset_id, page_size, offset))
            if not isinstance(page, list):
                raise CatalogError("MalformedData", "Apify dataset response is not an array")
            records.extend(page)
            if len(page) < page_size:
                break
            offset += len(page)
    run = wait_for_final_billing(client, run_id, len(records), 60)
    return run, records


def billing_is_final(run, result_record_count):
    counts = run.get("chargedEventCounts") or {}
    event_usage = run.get("eventUsage") or {}
    usage_total = run.get("usageTotalUsd")
    if usage_total is None or counts.get("result") != result_record_count:
        return False
    event_total = sum(Decimal(str(value.get("eventTotalUsd", 0))) for value in event_usage.values())
    return event_total == Decimal(str(usage_total))


def wait_for_final_billing(client, run_id, result_record_count, timeout_seconds):
    deadline = time.monotonic() + timeout_seconds
    while True:
        run = client.request("GET", "/v2/actor-runs/{}".format(run_id)).get("data", {})
        if run.get("status") != "SUCCEEDED" or billing_is_final(run, result_record_count):
            return run
        if time.monotonic() >= deadline:
            raise CatalogError("MissingProvenance", "Apify billing events did not reconcile for run {}".format(run_id))
        time.sleep(2)


def _next_id(conn, table, column, prefix):
    row = conn.execute("SELECT {} FROM {} WHERE {} LIKE ? ORDER BY {} DESC LIMIT 1".format(column, table, column, column), (prefix + "-%",)).fetchone()
    number = int(row[0].rsplit("-", 1)[1]) + 1 if row else 1
    return "{}-{:06d}".format(prefix, number)


def _require_schema_v6(conn):
    row = conn.execute("SELECT MAX(schema_version) FROM schema_meta").fetchone()
    if not row or row[0] < 6:
        raise CatalogError("SourceNotFound", "Schema version 6 is required; run inventory_catalog.py init")


def _dataset_identity_evidence(conn, dataset_id):
    evidence = {"handles": set(), "urls": set(), "names": set(), "locators": []}
    rows = conn.execute(
        "SELECT vo.visual_observation_id, vo.extracted_text, vo.structured_json "
        "FROM visual_observations vo JOIN visual_assets va ON va.visual_asset_id=vo.visual_asset_id "
        "WHERE va.dataset_id=?", (dataset_id,),
    ).fetchall()
    for observation_id, text, structured in rows:
        found = False
        if structured:
            try:
                value = json.loads(structured)
            except json.JSONDecodeError:
                value = None
            if isinstance(value, dict):
                identity = value.get("channel_identity") or {}
                handle = handle_key(identity.get("handle"))
                if handle:
                    evidence["handles"].add(handle)
                    found = True
                if identity.get("channel_name"):
                    evidence["names"].add(str(identity["channel_name"]).strip().casefold())
        for match in re.findall(r"youtube\.com/(@[A-Za-z0-9._-]+)", text or "", flags=re.I):
            evidence["handles"].add(handle_key(match))
            evidence["urls"].add(canonical_channel_url("https://www.youtube.com/" + match))
            found = True
        if found:
            evidence["locators"].append("visual_observation:{}".format(observation_id))
    return evidence


def reconcile_channel_identity(conn, dataset_id, requested_channel_url, channel,
                               allow_direct_apify_identity=False):
    youtube_id = channel["youtube_channel_id"]
    requested_handle = handle_key(handle_from_url(requested_channel_url))
    actor_handle = handle_key(channel["handle"])
    actor_url = canonical_channel_url(channel["channel_url"])
    evidence = _dataset_identity_evidence(conn, dataset_id)
    if allow_direct_apify_identity and requested_handle and actor_handle:
        if requested_handle != actor_handle:
            raise CatalogError(
                "EvidenceConflict",
                "Requested handle {} does not match Actor handle {}".format(
                    requested_handle, actor_handle
                ),
            )
        evidence["locators"].append("apify_actor_result:channel_identity")
    strong_match = bool(
        (actor_handle and actor_handle in evidence["handles"])
        or (requested_handle and requested_handle in evidence["handles"])
        or (actor_url and actor_url in evidence["urls"])
        or (allow_direct_apify_identity and requested_handle and requested_handle == actor_handle)
    )
    existing = conn.execute("SELECT * FROM channels WHERE youtube_channel_id=?", (youtube_id,)).fetchone()
    if not existing and actor_handle:
        existing = conn.execute("SELECT * FROM channels WHERE LOWER(handle)=?", (actor_handle,)).fetchone()
    if existing:
        if existing["youtube_channel_id"] and existing["youtube_channel_id"] != youtube_id:
            raise CatalogError("EvidenceConflict", "Existing channel handle maps to a different YouTube channel ID")
        return existing["channel_id"], False, evidence
    if not strong_match:
        raise CatalogError("AmbiguousIdentity", "No strong identifier links Actor channel {} to dataset {}".format(youtube_id, dataset_id))
    return None, True, evidence


def _run_value(run, key, fallback=None):
    return run[key] if run.get(key) is not None else fallback


def validate_run(run, actor_input, records, cost_cap):
    if run.get("status") != "SUCCEEDED":
        raise CatalogError("ToolFailure", "Actor run {} ended with status {}".format(run.get("id", "UNKNOWN"), run.get("status")))
    if run.get("actId") not in (None, ACTOR_ID):
        raise CatalogError("EvidenceConflict", "Actor run used unexpected Actor ID {}".format(run.get("actId")))
    if not run.get("id") or not run.get("startedAt") or not run.get("finishedAt"):
        raise CatalogError("MissingProvenance", "Actor run is missing ID/start/finish metadata")
    cost = run.get("usageTotalUsd")
    if cost is None:
        raise CatalogError("MissingProvenance", "Actor run is missing exact usageTotalUsd")
    if Decimal(str(cost)) > Decimal(str(cost_cap)):
        raise CatalogError("CostCapExceeded", "Actor run cost ${} exceeded ${} cap".format(cost, cost_cap))
    normalized, channel, validation = validate_records(records)
    return normalized, channel, validation


