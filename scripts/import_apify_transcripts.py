#!/usr/bin/env python3
"""Import Apify srd836/youtube-transcript-pro dataset JSON(s) into senior_health_complete.db.
Usage: python3 scripts/import_apify_transcripts.py file1.json [file2.json ...]
Only status=success rows for video_ids already in `videos` are imported; existing transcripts are kept."""
import sys, json, hashlib, sqlite3, re

DB = 'data/catalog/senior_health_complete.db'
con = sqlite3.connect(DB)
known = {r[0] for r in con.execute('select video_id from videos')}
have = {r[0] for r in con.execute('select video_id from transcripts')}
added = skipped = 0
for path in sys.argv[1:]:
    for r in json.load(open(path)):
        vid, txt = r.get('videoId'), (r.get('plainText') or '').strip()
        if r.get('status') != 'success' or not txt or vid not in known or vid in have:
            skipped += 1
            continue
        con.execute('insert into transcripts values(?,?,?,?,?,?,?)',
                    (vid, txt, len(txt.split()), r.get('languageCode'),
                     'auto_generated' if r.get('isAutoGenerated') else 'user_generated',
                     hashlib.sha256(txt.encode()).hexdigest(), 'apify_youtube-transcript-pro'))
        have.add(vid)
        added += 1
con.execute('update videos set has_transcript=1 where video_id in (select video_id from transcripts)')
con.execute('update channels set transcripts_in_db=(select count(*) from videos v where v.channel_id=channels.channel_id and v.has_transcript=1)')
con.commit()
print('added', added, 'skipped', skipped)
